export function currencyForPhone(phone?: string | null): string {
  const normalized = phone?.replace(/[\s\-()]/g, '') ?? '';
  return callingCodeCurrencies.find(([code]) => normalized.startsWith(code))?.[1] ?? 'PKR';
}
